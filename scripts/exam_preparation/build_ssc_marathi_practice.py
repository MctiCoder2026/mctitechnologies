for text, options, correct, category, year in QUESTIONS:
    source_name, source_ref = SOURCES[year]

    q, q_created = AssessmentQuestion.objects.get_or_create(
        assessment=assessment,
        question_text=text,
        board_year=year,
        defaults={
            "category": category,
            "order": assessment.questions.count() + 1,
            "marks": 1,
            "is_active": True,
            "question_origin": "board_based",
            "source_name": source_name,
            "source_reference": source_ref,
        },
    )

    if q_created:
        for i, option in enumerate(options):
            AssessmentOption.objects.create(
                question=q,
                option_text=option,
                is_correct=(i == correct),
                order=i + 1,
            )
        added += 1

