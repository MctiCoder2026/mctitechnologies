def add_question(text, options, correct, category, year, origin):
    source_name, source_ref = SOURCES[year]

    q, created = AssessmentQuestion.objects.get_or_create(
        assessment=assessment,
        question_text=text,
        board_year=year,
        defaults={
            "category": category,
            "order": assessment.questions.count() + 1,
            "marks": 1,
            "is_active": True,
            "question_origin": origin,
            "source_name": source_name,
            "source_reference": source_ref,
        },
    )

    if created:
        for i, option in enumerate(options):
            AssessmentOption.objects.create(
                question=q,
                option_text=option,
                is_correct=(i == correct),
                order=i + 1,
            )

    return created


